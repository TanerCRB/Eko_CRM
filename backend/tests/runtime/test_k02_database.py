"""K-02: the database the composition created and `migrate` brought to its first revision.

Every assertion targets the application database `eko`, created by the init content; the test
creates no database and runs no `alembic upgrade` of its own.
"""

import pytest

from tests.runtime.conftest import Started
from tests.support import db_checks as dc

pytestmark = pytest.mark.runtime

LIBC_FIXTURE_DB = "k02_libc_fixture"


def test_k02_c1_server_is_postgresql_18(running: Started) -> None:
    [[version]] = running.composition.sql("SHOW server_version_num")
    assert dc.c1_version(int(version)) == []


def test_k02_c2_one_head_and_alembic_version_holds_it(running: Started) -> None:
    composition = running.composition
    heads = composition.compose("exec", "-T", "backend", "alembic", "heads").stdout
    stamped = [row[0] for row in composition.sql("SELECT version_num FROM alembic_version")]
    assert dc.c2_heads(heads, stamped) == []


def test_k02_c3_alembic_check_exits_zero(running: Started) -> None:
    result = running.composition.compose("exec", "-T", "backend", "alembic", "check", check=False)
    assert result.returncode == 0, result.stderr[-2000:]


def test_k02_c6_no_naive_timestamp_column(running: Started) -> None:
    rows = running.composition.sql(
        "SELECT table_name, column_name FROM information_schema.columns "
        "WHERE table_schema = 'public' AND data_type = 'timestamp without time zone'"
    )
    assert dc.c6_naive_columns([(r[0], r[1]) for r in rows]) == []


def test_k02_c5_utf8_and_icu_pl_pl(running: Started) -> None:
    composition = running.composition
    [[encoding]] = composition.sql("SHOW server_encoding")
    [[provider, locale]] = composition.sql(
        "SELECT datlocprovider, datlocale FROM pg_database WHERE datname = current_database()"
    )
    [[database]] = composition.sql("SELECT current_database()")
    assert database == "eko"
    assert dc.c5_database(encoding, provider, locale or None) == []


def test_k02_c5_contrast_a_libc_database_fails(running: Started) -> None:
    composition = running.composition
    composition.sql(
        f"CREATE DATABASE {LIBC_FIXTURE_DB} LOCALE_PROVIDER libc TEMPLATE template0", "postgres"
    )
    try:
        [[encoding]] = composition.sql("SHOW server_encoding", LIBC_FIXTURE_DB)
        [[provider, locale]] = composition.sql(
            "SELECT datlocprovider, datlocale FROM pg_database WHERE datname = current_database()",
            LIBC_FIXTURE_DB,
        )
        assert dc.c5_database(encoding, provider, locale or None) != []
    finally:
        composition.sql(f"DROP DATABASE {LIBC_FIXTURE_DB}", "postgres")


C3_CONTRAST = """
import sys
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Column, Integer, Table
from app.data.base import Base
Table("k02_unmigrated_fixture", Base.metadata, Column("id", Integer, primary_key=True))
try:
    command.check(Config("alembic.ini"))
except AutogenerateDiffsDetected:
    sys.exit(3)
sys.exit(0)
"""


def test_k02_c3_contrast_a_model_table_with_no_revision_fails(running: Started) -> None:
    result = running.composition.python_in_backend(C3_CONTRAST)
    assert result.returncode == 3, result.stderr[-2000:]


C6_CONTRAST = """
import psycopg, os, sys
from app.core.settings import Settings, load_settings
s = load_settings(Settings)
with psycopg.connect(host=s.app_db_host, dbname=s.app_db_name, user=s.app_db_user,
                     password=s.app_db_password.get_secret_value()) as conn:
    conn.execute("CREATE TABLE k02_naive_fixture (starts_at timestamp)")
    rows = conn.execute(
        "SELECT table_name, column_name FROM information_schema.columns "
        "WHERE table_schema = 'public' AND data_type = 'timestamp without time zone'"
    ).fetchall()
    conn.rollback()
for table, column in rows:
    sys.stdout.write(table + "\\t" + column + "\\n")
"""


def test_k02_c6_contrast_a_naive_timestamp_column_fails(running: Started) -> None:
    result = running.composition.python_in_backend(C6_CONTRAST)
    assert result.returncode == 0, result.stderr[-2000:]
    rows = [tuple(line.split("\t")) for line in result.stdout.splitlines() if line]
    assert dc.c6_naive_columns([(r[0], r[1]) for r in rows]) != []
    gone = running.composition.sql("SELECT to_regclass('public.k02_naive_fixture') IS NULL")
    assert gone == [["t"]]
